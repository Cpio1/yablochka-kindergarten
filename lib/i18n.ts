export function isLocale(v: string): v is Locale {
  return (locales as readonly string[]).includes(v);
}

/** Русская версия живёт в корне «/», казахская — в «/kk». */
export function localePath(l: Locale): string {
  return l === "ru" ? "/" : "/kk";
}

